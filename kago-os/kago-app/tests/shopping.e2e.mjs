  await page.screenshot({ path: `${output}/cart-mobile.png`, fullPage: true });
  pass("own DB cart restored; shared localStorage ignored; APP-02 controls enabled");
  await page.reload();
  await waitText("ログイン中の利用者の買い物");
  snapshot = await (await context.request.get(`${origin}/api/shopping`)).json();
  assert.equal(snapshot.visit.id, uuid(13));
  assert.equal(snapshot.cart[0].price * snapshot.cart[0].quantity, 642);
  pass("reload preserves the same visit and DB cart");
  await page.getByRole("link", { name: "マイページを開く" }).click();
  await waitText("ログイン中の買い物");
  assert.equal(await page.getByText("佐藤 美咲", { exact: true }).count(), 0);
  await page.getByRole("link", { name: "買い物画面へ戻る" }).click();
  await waitText("ログイン中の利用者の買い物");
  pass("account page never renders the old fixed user's profile/history");
  await page.getByRole("button", { name: "店舗・来店を選ぶ" }).click();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "空のかごで新しく来店する" }).click();
